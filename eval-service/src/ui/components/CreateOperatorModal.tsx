import { useState } from 'react';
import {
  AlertCircle,
  BarChart3,
  Calculator,
  Code2,
  Compass,
  Database,
  Plus,
  Workflow,
  X,
} from 'lucide-react';
import {
  evalApi,
  type MetricDomainTag,
  type OperatorCategory,
  type V4OperatorEngineKind,
  type V4OperatorItem,
} from '../api.ts';

interface CreateOperatorModalProps {
  isOpen: boolean;
  onClose: () => void;
  existingOperators: V4OperatorItem[];
  onCreated: (newOp: V4OperatorItem, openCanvas?: boolean) => Promise<void> | void;
}

const CATEGORY_OPTIONS: Array<{
  id: OperatorCategory;
  domainTag: MetricDomainTag;
  label: string;
  desc: string;
}> = [
  { id: 'effectiveness', domainTag: 'firepower', label: '效能域 (Effectiveness)', desc: '毁伤、命中、突防等作战实效二维事实表' },
  { id: 'time', domainTag: 'synergy', label: '时效域 (Time)', desc: '发现响应耗时、协同闭环时间等时序事实表' },
  { id: 'situation', domainTag: 'isr', label: '态势域 (Situation)', desc: '空情覆盖、目标跟踪保真度、信噪比态势事实表' },
  { id: 'compliance', domainTag: 'c2', label: '合规域 (Compliance)', desc: '任务走廊遵从、空域安全裕度、规则约束事实表' },
  { id: 'cost', domainTag: 'cost', label: '成本域 (Cost)', desc: '弹药消耗、油耗、战损成本等资源事实表' },
];

const ALGO_MODE_OPTIONS: Array<{
  id: V4OperatorEngineKind;
  label: string;
  desc: string;
  icon: typeof Calculator;
  color: string;
}> = [
  {
    id: 'inline_calc',
    label: '公式计算 (LibFormula)',
    desc: '基于行内数学与逻辑表达式快速衍生新字段',
    icon: Calculator,
    color: 'text-cyan-400 border-cyan-500/30 bg-cyan-500/10',
  },
  {
    id: 'group_agg',
    label: '数据汇总 (Group By 聚合)',
    desc: '按主键分组汇总求均值、样本数、极值与累加值',
    icon: BarChart3,
    color: 'text-amber-400 border-amber-500/30 bg-amber-500/10',
  },
  {
    id: 'spatial',
    label: '空间几何 (4D 走廊/时空裕度)',
    desc: '空间几何点面包含、空域安全裕度判定',
    icon: Compass,
    color: 'text-violet-400 border-violet-500/30 bg-violet-500/10',
  },
  {
    id: 'python_script',
    label: 'Python 科学计算',
    desc: 'Pandas/NumPy 复杂矩阵运算、拟合与高阶特征提取',
    icon: Code2,
    color: 'text-fuchsia-400 border-fuchsia-500/30 bg-fuchsia-500/10',
  },
  {
    id: 'data_input',
    label: '底表直连 (Data Input)',
    desc: '从仿真输出事件表中直接提取与清洗核心字段，输出二维事实表',
    icon: Database,
    color: 'text-blue-400 border-blue-500/30 bg-blue-500/10',
  },
];

const DEFAULT_PYTHON_TEMPLATE = `# V4 算子沙箱脚本：通过 T('TableName') 读取仿真事件表，最终输出 output_df (含 Side 列)
df = T('WeaponFired')
if df is None or df.empty:
    output_df = pd.DataFrame(columns=['Side', 'EventCount'])
else:
    side_col = 'FiringUnitSide' if 'FiringUnitSide' in df.columns else df.columns[0]
    output_df = (
        df.groupby(side_col, dropna=False)
        .size()
        .reset_index(name='EventCount')
        .rename(columns={side_col: 'Side'})
    )
`;

export function CreateOperatorModal({
  isOpen,
  onClose,
  existingOperators,
  onCreated,
}: CreateOperatorModalProps) {
  if (!isOpen) return null;

  const [name, setName] = useState('');
  const [operatorId, setOperatorId] = useState('');
  const [idAutoGenerated, setIdAutoGenerated] = useState(true);
  const [category, setCategory] = useState<OperatorCategory>('effectiveness');
  const [engineKind, setEngineKind] = useState<V4OperatorEngineKind>('inline_calc');
  const [description, setDescription] = useState('');
  const [initDefaultPipeline, setInitDefaultPipeline] = useState(true);

  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const handleNameChange = (val: string) => {
    setName(val);
    if (idAutoGenerated) {
      const sanitized = val.toLowerCase().replace(/[^a-z0-9_]/g, '');
      const prefix =
        category === 'effectiveness'
          ? 'eff'
          : category === 'compliance'
          ? 'comp'
          : category === 'time'
          ? 'time'
          : category === 'situation'
          ? 'sit'
          : 'cost';
      const suffix = Date.now().toString().slice(-4);
      setOperatorId(`custom.${prefix}_${sanitized || 'op'}_${suffix}`);
    }
  };

  const handleIdChange = (val: string) => {
    setIdAutoGenerated(false);
    setOperatorId(val);
  };

  const handleSubmit = async (openCanvas: boolean) => {
    setErrorMsg(null);
    const trimmedName = name.trim();
    const trimmedId = operatorId.trim();

    if (!trimmedName) {
      setErrorMsg('请输入算子中文名称');
      return;
    }
    if (!trimmedId) {
      setErrorMsg('请输入算子唯一标识 (ID)');
      return;
    }
    if (existingOperators.some((o) => o.id === trimmedId)) {
      setErrorMsg(`算子标识 [${trimmedId}] 已存在，请更换`);
      return;
    }

    setSubmitting(true);
    try {
      const catMeta = CATEGORY_OPTIONS.find((c) => c.id === category) ?? CATEGORY_OPTIONS[0];
      const res = await evalApi.upsertV4Operator({
        id: trimmedId,
        name: trimmedName,
        chapter: 99,
        category,
        militaryLevel: 'MOP',
        domainTag: catMeta.domainTag,
        description:
          description.trim() ||
          `【${trimmedName}】自定义 V4 算子，专注底表清洗与二维事实表 (TableDataset) 产出。`,
        layer: 'fact',
        engineKind,
        requiredTables: ['WeaponFired'],
        optionalTables: [],
        parameterPorts: [],
        outputColumns:
          engineKind === 'python_script'
            ? ['Side', 'EventCount']
            : engineKind === 'group_agg'
            ? ['Side', 'avg_damage']
            : ['Side', 'score_metric'],
        pythonCode: engineKind === 'python_script' ? DEFAULT_PYTHON_TEMPLATE : '',
      });

      const createdOp = res.operator;

      if (initDefaultPipeline) {
        const inputNodeId = `node_input_${Date.now()}`;
        const calcNodeId = `node_core_${Date.now()}`;
        const outNodeId = `node_out_${Date.now()}`;
        const coreNodeType = engineKind === 'data_input' ? 'inline_calc' : engineKind;

        const nodes = [
          {
            id: inputNodeId,
            type: 'data_input' as const,
            title: '表输入：样本切片数据源',
            description: '接入仿真规范事件表或时序航迹数据源',
            x: 80,
            y: 180,
            config: {
              sourceType: 'csv',
              csvTable: 'WeaponFired',
              selectedColumns: ['WeaponID', 'FiringUnitID', 'TargetUnitID', 'FiringUnitSide'],
            },
            runtime: { status: 'idle' as const },
          },
          {
            id: calcNodeId,
            type: coreNodeType,
            title: `${trimmedName} · 核心计算`,
            description: `配置本算子专有${coreNodeType === 'group_agg' ? '跨行汇总' : coreNodeType === 'spatial' ? '空间几何' : coreNodeType === 'python_script' ? 'Python 沙箱' : '算法公式'}计算逻辑`,
            x: 480,
            y: 180,
            config:
              coreNodeType === 'group_agg'
                ? {
                    groupKeys: ['FiringUnitSide'],
                    aggregations: [
                      { outputField: 'avg_damage', sourceField: 'WeaponID', method: 'COUNT_ALL' },
                    ],
                  }
                : coreNodeType === 'inline_calc'
                ? {
                    derivedColumns: [
                      { name: 'score_metric', expression: '1', dataType: 'number' },
                    ],
                  }
                : coreNodeType === 'python_script'
                ? {
                    pythonCode: DEFAULT_PYTHON_TEMPLATE,
                  }
                : {},
            runtime: { status: 'idle' as const },
          },
          {
            id: outNodeId,
            type: 'result_output' as const,
            title: `二维表输出：${trimmedName}`,
            description: '输出结构化特征表，供上层指标计算引用',
            x: 920,
            y: 180,
            config: {
              targetField:
                coreNodeType === 'group_agg'
                  ? 'avg_damage'
                  : coreNodeType === 'inline_calc'
                  ? 'score_metric'
                  : 'EventCount',
            },
            runtime: { status: 'idle' as const },
          },
        ];

        const edges = [
          { id: `edge_1_2_${Date.now()}`, sourceNodeId: inputNodeId, targetNodeId: calcNodeId, label: '输入数据流' },
          { id: `edge_2_3_${Date.now()}`, sourceNodeId: calcNodeId, targetNodeId: outNodeId, label: '特征计算流' },
        ];

        await evalApi.saveOperatorPipeline({
          operatorId: trimmedId,
          pipelineTitle: `${trimmedName} · 算法流水线`,
          nodes,
          edges,
        });
      }

      onClose();
      await onCreated(createdOp, openCanvas);
    } catch (err) {
      setErrorMsg(`创建算子失败: ${err instanceof Error ? err.message : String(err)}`);
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 backdrop-blur-sm p-4">
      <div className="w-full max-w-3xl max-h-[90vh] rounded-2xl border border-slate-800 bg-[#0d1424] shadow-2xl flex flex-col overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        <div className="flex items-center justify-between border-b border-slate-800 bg-[#0a0f1d] px-6 py-4 shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-emerald-500/15 border border-emerald-500/30 text-emerald-400">
              <Plus className="h-5 w-5" />
            </div>
            <div>
              <h2 className="text-base font-bold text-slate-100">新建自定义 V4 评估算子</h2>
              <span className="text-xs text-slate-400">
                注册新特征计算算子（存入 V4 SQLite 算子库），支持在画布中编排多节点流水线
              </span>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-800 hover:text-slate-100 transition"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto px-6 py-5 space-y-4 text-xs">
          {errorMsg && (
            <div className="flex items-center gap-2 rounded-xl border border-rose-500/40 bg-rose-500/15 p-3 text-rose-300">
              <AlertCircle className="h-4 w-4 shrink-0" />
              <span>{errorMsg}</span>
            </div>
          )}

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-200">
                算子名称 <span className="text-rose-400">*</span>
              </label>
              <input
                type="text"
                placeholder="例如: 传感器连续跟踪保持率"
                value={name}
                onChange={(e) => handleNameChange(e.target.value)}
                className="w-full rounded-xl border border-slate-700 bg-slate-900/90 px-3 py-2 text-xs text-slate-100 placeholder-slate-500 focus:border-emerald-500 focus:outline-none transition"
              />
            </div>

            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-slate-200">
                  算子标识 (ID) <span className="text-rose-400">*</span>
                </label>
                {idAutoGenerated && (
                  <span className="text-[10px] text-emerald-400 font-mono">根据名称自动生成</span>
                )}
              </div>
              <input
                type="text"
                placeholder="例如: custom.eff_sensor_track_rate"
                value={operatorId}
                onChange={(e) => handleIdChange(e.target.value)}
                className="w-full rounded-xl border border-slate-700 bg-slate-900/90 px-3 py-2 text-xs font-mono text-cyan-300 placeholder-slate-500 focus:border-emerald-500 focus:outline-none transition"
              />
            </div>
          </div>

          <div className="space-y-1.5">
            <label className="text-xs font-semibold text-slate-200">
              所属评估业务领域 (Category)
            </label>
            <div className="grid grid-cols-2 sm:grid-cols-5 gap-2">
              {CATEGORY_OPTIONS.map((cat) => (
                <button
                  key={cat.id}
                  type="button"
                  onClick={() => setCategory(cat.id)}
                  className={`flex flex-col p-2.5 rounded-xl border text-left transition ${
                    category === cat.id
                      ? 'border-emerald-500 bg-emerald-500/15 text-emerald-200 shadow-sm'
                      : 'border-slate-800 bg-slate-900/60 text-slate-400 hover:border-slate-700 hover:text-slate-200'
                  }`}
                >
                  <span className="font-semibold text-xs">{cat.label.split(' ')[0]}</span>
                  <span className="text-[10px] text-slate-500 mt-1 line-clamp-1">{cat.desc}</span>
                </button>
              ))}
            </div>
          </div>

          <div className="space-y-1.5">
            <label className="text-xs font-semibold text-slate-200">
              核心计算引擎 (EngineKind)
            </label>
            <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-2">
              {ALGO_MODE_OPTIONS.map((opt) => (
                <button
                  key={opt.id}
                  type="button"
                  onClick={() => setEngineKind(opt.id)}
                  className={`flex items-start gap-2.5 p-2.5 rounded-xl border text-left transition ${
                    engineKind === opt.id
                      ? `${opt.color} border-current ring-1 ring-emerald-500/50`
                      : 'border-slate-800 bg-slate-900/60 text-slate-400 hover:border-slate-700 hover:text-slate-200'
                  }`}
                >
                  <opt.icon className="h-4 w-4 mt-0.5 shrink-0" />
                  <div>
                    <div className="font-semibold text-xs text-slate-100">{opt.label}</div>
                    <div className="text-[10px] text-slate-400 mt-0.5">{opt.desc}</div>
                  </div>
                </button>
              ))}
            </div>
          </div>

          <div className="space-y-1.5">
            <label className="text-xs font-semibold text-slate-200">
              算子业务定义说明
            </label>
            <textarea
              rows={2}
              placeholder="简述该算子的物理意义、计算口径及战场评估应用场景..."
              value={description}
              onChange={(e) => setDescription(e.target.value)}
              className="w-full rounded-xl border border-slate-700 bg-slate-900/90 px-3 py-2 text-xs text-slate-100 placeholder-slate-500 focus:border-emerald-500 focus:outline-none transition resize-none"
            />
          </div>

          <div className="flex items-center gap-2 rounded-xl border border-slate-800 bg-slate-900/50 p-3">
            <input
              type="checkbox"
              id="initPipelineCheckbox"
              checked={initDefaultPipeline}
              onChange={(e) => setInitDefaultPipeline(e.target.checked)}
              className="h-4 w-4 rounded border-slate-700 bg-slate-900 text-emerald-500 focus:ring-emerald-500"
            />
            <label htmlFor="initPipelineCheckbox" className="text-xs text-slate-300 cursor-pointer">
              <strong>自动初始化标准流水线拓扑</strong>：自动生成 [表输入 ➔ 核心计算 ➔ 二维表输出] 3 节点标准编排。
            </label>
          </div>
        </div>

        <div className="flex items-center justify-between border-t border-slate-800 bg-[#0a0f1d] px-6 py-3.5 shrink-0">
          <button
            type="button"
            onClick={onClose}
            className="rounded-xl border border-slate-700 bg-slate-800 px-4 py-2 text-xs font-semibold text-slate-300 hover:bg-slate-700 hover:text-white transition"
          >
            取消
          </button>

          <div className="flex items-center gap-2.5">
            <button
              type="button"
              disabled={submitting}
              onClick={() => handleSubmit(false)}
              className="rounded-xl border border-slate-700 bg-slate-800/90 px-4 py-2 text-xs font-semibold text-slate-200 hover:bg-slate-700 hover:text-white transition shadow-sm disabled:opacity-50"
            >
              {submitting ? '保存中...' : '仅保存算子'}
            </button>

            <button
              type="button"
              disabled={submitting}
              onClick={() => handleSubmit(true)}
              className="flex items-center gap-1.5 rounded-xl border border-emerald-500/50 bg-gradient-to-r from-emerald-600 to-teal-600 px-4 py-2 text-xs font-bold text-white hover:from-emerald-500 hover:to-teal-500 transition shadow-lg shadow-emerald-950/40 disabled:opacity-50"
            >
              <Workflow className="h-4 w-4" />
              <span>{submitting ? '创建中...' : '保存并进入画布编排'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
